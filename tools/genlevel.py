#!/usr/bin/env python3
"""genlevel - glider's sectors: entity tables and the sector directory.

Each sector (engine spec section 6) is an 8192-unit square that wraps
both ways, with its static entities (towers, blocks, mines) and its
generator crystals, which launch the enemy gliders. Sector 1 is the M3
test sector as played (made 2026-09-29/10-04 by a scratchpad script,
seed 11), kept verbatim; the others are generated by the same rules:

- a 5 x 5 grid of sites at a pitch of 8192/5, each jittered up to 450,
  the sites within 900 of the spawn dropped; towers, blocks and mines
  dealt to them at random headings (more sites drawn if needed), an
  optional 2 x 2 cluster of towers 384 apart (the heavy view);
- no two entities closer than 380 counting the wrap;
- crystals in open ground (825 or more from any other entity, 2500
  from each other), the first about 2500 ahead of the spawn so one is
  in view at the start; their first launches staggered 150 beats.

Positions are listed in -4096..4095 around the spawn (128, 128),
every entity seen at its nearest image. Each sector also has its rules
(RULES below: what makes one harder than the last) and a caption for
its card. The sectors are a ladder (engine spec 11.2): each adds one
thing to the one before, then a second lap over the same tables with
everything stepped up (harder()), which the game repeats from then on
with the launch delay cut each time. The output, levels.inc, is a
directory of sector records (the sd_* layout in equates.inc: the
table's offset from `levels`, the spawn x, z and heading, the launch
delay in beats, the rules, the caption's offset from `levels`), the
tables in the entity-record format (mesh, flags, x, z, centre height,
heading, hits, timer; -1 ends a table) and the captions.

    python tools/genlevel.py > glider/levels.inc
    python tools/genlevel.py --png maps.png      # the sectors from above

Seeded: the same build every time. Stdlib only.
"""

import argparse
import math
import random
import sys

SECTOR = 8192
SPAWN = (128, 128)
MIN_GAP = 380
GEN_CLEAR = 825
GEN_SPREAD = 2500
HEIGHT = {"tower": "yb_tower", "block": "yb_block", "mine": "cam_h",
          "gen": "yb_gen"}

# Sector 1: the M3 test sector, as level.inc had it (kind, x, z,
# heading in brads, first launch for a crystal)
SECTOR1 = [
    ("gen", 300, 2600, 40, 150), ("gen", -2400, -2500, 200, 300),
    ("gen", 2300, -1000, 110, 450),
    ("block", -308, -3713, 126, 0), ("tower", -2004, -3454, 51, 0),
    ("tower", 2800, -3300, 0, 0), ("tower", 3184, -3300, 0, 0),
    ("mine", -3320, -3223, 5, 0), ("tower", 1656, -3151, 30, 0),
    ("tower", 2800, -2916, 0, 0), ("tower", 3184, -2916, 0, 0),
    ("tower", 26, -2035, 238, 0), ("mine", -2895, -1669, 249, 0),
    ("mine", 1638, -1492, 90, 0), ("mine", -2007, -1360, 96, 0),
    ("tower", -1464, -412, 229, 0), ("mine", 1600, -200, 97, 0),
    ("block", 3516, -90, 67, 0), ("tower", -3270, 79, 214, 0),
    ("mine", 3589, 1536, 196, 0), ("mine", -423, 1606, 59, 0),
    ("block", -3561, 1649, 202, 0), ("tower", -1204, 2057, 215, 0),
    ("tower", 2086, 2085, 108, 0), ("block", -1500, 3381, 0, 0),
    ("block", 1945, 3464, 138, 0), ("block", -3160, 3540, 155, 0),
    ("tower", -54, 3585, 10, 0), ("tower", 3689, 3589, 107, 0),
]

# A sector's rules, the record after the launch delay (sd_own on, in
# this order): the gliders a crystal keeps up (own; under the global
# cap ngl = 4, the frame budget's knob), the range inside which a
# patrolling glider attacks (alert; under lose_r 3500, where it gives
# up), the types launched in turn (mix: MIX_N of them, so cycles of 1, 2,
# 3 or 6), a crystal's hits (ghp), the range inside which it fires at
# the craft (frange; 0 = it holds its fire) and the beats between its
# shots (fcd), the enemy shots' speed (esv, units a beat; their life
# keeps the range at ESHOT_RANGE), the shield the warp into the sector
# restores (gain; SHIELD_MAX = full). These are the rules before
# sector 1: each sector's own dict is the change from the sector
# before it, so the ladder's rules add up.
RULES = dict(own=2, alert=1800, mix=("dart", "wedge", "kite") * 2, ghp=5,
             frange=1500, fcd=75, esv=40, gain=8)
TYPES = ("dart", "wedge", "kite")   # types.inc, in order
MIX_N = 6                           # equates.inc mix_n
NGL, LOSE_R, SHIELD_MAX = 4, 3500, 8    # equates.inc
DLY_MIN = 200                       # equates.inc dly_min
ESHOT_RANGE = 1800
SD_SIZE = 34                        # the record's bytes (equates.inc sd_*)
CAPTION_MAX = 26                    # characters across the card (tx_med)
FONT = set(" -./0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZ")    # genfont.py

# The ladder, each sector one thing more than the last, which its
# caption names on the card: sector 1 has darts and wedges and silent
# crystals; then the crystals fire, the kites join, a minefield, harder
# crystals, the swarm (more gliders up, attacking from further), faster
# shots more often from further, and a fortress of 7 crystals with a
# kite-heavy mix. The sector's crystals, mines and launch delay come
# with its table. Sectors 1-3 keep the Beta 1 tables.
SECTORS = [
    dict(fixed=SECTOR1, delay=500, caption="DESTROY THE 3 CRYSTALS",
         rules=dict(frange=0, mix=("dart", "wedge") * 3)),
    dict(seed=23, towers=8, blocks=6, mines=9, gens=4, delay=450,
         cluster=(-1, 1), caption="THE CRYSTALS FIRE BACK",
         rules=dict(frange=1500)),
    dict(seed=41, towers=7, blocks=6, mines=11, gens=5, delay=420,
         cluster=None, caption="GUNSHIPS JOIN IN",
         rules=dict(mix=("dart", "wedge", "kite") * 2)),
    dict(seed=59, towers=5, blocks=3, mines=22, gens=5, delay=400,
         cluster=None, caption="MINEFIELD", rules=dict()),
    dict(seed=67, towers=8, blocks=6, mines=10, gens=5, delay=380,
         cluster=None, caption="CRYSTALS TAKE 8 HITS",
         rules=dict(ghp=8)),
    dict(seed=73, towers=8, blocks=5, mines=11, gens=6, delay=320,
         cluster=None, caption="THE SWARM",
         rules=dict(own=3, alert=2400)),
    dict(seed=83, towers=9, blocks=5, mines=11, gens=6, delay=320,
         cluster=None, caption="SHARPSHOOTER CRYSTALS",
         rules=dict(frange=1800, fcd=45, esv=60)),
    dict(seed=95, towers=8, blocks=5, mines=12, gens=7, delay=300,
         cluster=(1, -1), caption="THE FORTRESS: 7 CRYSTALS",
         rules=dict(mix=("kite", "wedge", "kite", "dart", "kite", "wedge"))),
]
LOOP_CAPTION = "HARDER STILL"


def harder(r, delay):
    """The loop's step: the same sector with everything stepped up --
    one more glider a crystal, an earlier alert, two more hits, every
    crystal firing, from further, half again as often, faster shots,
    3 less shield at the warp, a launch delay 100 shorter."""
    return dict(r, own=min(r["own"] + 1, NGL),
                alert=min(r["alert"] + 400, 3000),
                ghp=r["ghp"] + 2,
                frange=min(r["frange"] + 300, ESHOT_RANGE) if r["frange"]
                else 1500,
                fcd=max(round(r["fcd"] * 2 / 3), 30),
                esv=min(r["esv"] + 10, 80),
                gain=max(r["gain"] - 3, 2)), max(delay - 100, DLY_MIN)


def wrap(d):
    return (d + SECTOR // 2) % SECTOR - SECTOR // 2


def dist(a, b):
    return math.hypot(wrap(a[0] - b[0]), wrap(a[1] - b[1]))


def generate(cfg):
    rng = random.Random(cfg["seed"])
    ents = []                       # (kind, x, z, heading, timer)

    def free(p, gap):
        return all(dist(p, (e[1], e[2])) >= gap for e in ents)

    if cfg.get("cluster"):
        sx, sz = cfg["cluster"]
        cx, cz = SPAWN[0] + sx * 3000, SPAWN[1] + sz * 3000
        for dx in (0, 384):
            for dz in (0, 384):
                ents.append(("tower", wrap(cx + dx), wrap(cz + dz), 0, 0))
    pitch = SECTOR / 5
    sites = []
    for i in range(5):
        for j in range(5):
            x = -SECTOR / 2 + pitch * (i + 0.5) + rng.uniform(-450, 450)
            z = -SECTOR / 2 + pitch * (j + 0.5) + rng.uniform(-450, 450)
            p = (round(wrap(x + SPAWN[0])), round(wrap(z + SPAWN[1])))
            if dist(p, SPAWN) >= 900:
                sites.append(p)
    rng.shuffle(sites)
    kinds = (["tower"] * cfg["towers"] + ["block"] * cfg["blocks"]
             + ["mine"] * cfg["mines"])
    for kind in kinds:
        while True:
            p = sites.pop() if sites else (rng.randrange(-4096, 4096),
                                           rng.randrange(-4096, 4096))
            if dist(p, SPAWN) >= 900 and free(p, MIN_GAP):
                break
        ents.append((kind, p[0], p[1], rng.randrange(256), 0))
    gens = []
    for k in range(cfg["gens"]):
        for _ in range(100000):
            if k == 0:              # one in view ahead at the start
                p = (SPAWN[0] + rng.randrange(-300, 300),
                     SPAWN[1] + rng.randrange(2400, 2600))
            else:
                p = (rng.randrange(-4096, 4096), rng.randrange(-4096, 4096))
            if (free(p, GEN_CLEAR) and dist(p, SPAWN) >= 1500
                    and all(dist(p, (g[1], g[2])) >= GEN_SPREAD for g in gens)):
                break
        else:
            sys.exit(f"genlevel: no room for crystal {k + 1} (seed {cfg['seed']})")
        gens.append(("gen", wrap(p[0]), wrap(p[1]), rng.randrange(256),
                     150 * (k + 1)))
    rest = sorted(ents, key=lambda e: (e[2], e[1]))
    return gens + rest


def check(ents):
    kinds = [e[0] for e in ents]
    assert kinds.count("gen") >= 1
    for i, a in enumerate(ents):
        assert -4096 <= a[1] < 4096 and -4096 <= a[2] < 4096, a
        for b in ents[i + 1:]:
            # (sector 1 rounded its crystal clearance: 824.8 passes)
            gap = GEN_CLEAR - 1 if "gen" in (a[0], b[0]) else 0
            assert dist(a[1:3], b[1:3]) >= max(gap, 380) or (
                a[0] == b[0] == "tower" and dist(a[1:3], b[1:3]) >= 384), (a, b)
    assert len(ents) + 4 <= 64, "the entity pool holds 64 (4 for gliders)"
    assert kinds.count("gen") <= 8, "ngen is 8"


def rules(r):
    assert set(r) == set(RULES), r
    assert 1 <= r["own"] <= NGL, r
    assert 0 < r["alert"] < LOSE_R, r
    assert len(r["mix"]) == MIX_N and set(r["mix"]) <= set(TYPES), r
    assert 1 <= r["ghp"] <= 1000, r
    # (within the shots' reach, and under half a sector: nearest image)
    assert r["frange"] == 0 or 300 <= r["frange"] <= ESHOT_RANGE, r
    assert 1 <= r["fcd"] <= 32767, r
    assert 8 <= r["esv"] <= 120, r
    assert 0 <= r["gain"] <= SHIELD_MAX, r
    return r


def build():
    """The ladder: (table number, entities, rules, launch delay,
    caption) per sector, the first lap then the loop's."""
    lap, r = [], dict(RULES)
    for i, cfg in enumerate(SECTORS, 1):
        ents = cfg["fixed"] if "fixed" in cfg else generate(cfg)
        check(ents)
        r = rules(dict(r, **cfg.get("rules", {})))
        assert DLY_MIN <= cfg["delay"] <= 32767, cfg
        lap.append((i, ents, r, cfg["delay"], cfg["caption"]))
    loop = [(i, ents) + harder(r, dly) + (LOOP_CAPTION,)
            for i, ents, r, dly, _ in lap]
    for _, _, r, _, cap in lap + loop:
        rules(r)
        assert len(cap) <= CAPTION_MAX and set(cap) <= FONT, cap
    return lap, loop


def emit(lap, loop):
    print("; levels.inc -- glider's sectors (generated by tools/genlevel.py:")
    print("; edit there). sec_dir: a record per sector (sd_*, equates.inc):")
    print("; its table's offset from levels, the spawn x, z and heading (8.8")
    print("; brads), the launch delay in beats; the gliders a crystal keeps")
    print("; up, their alert range, the types launched in turn; a crystal's")
    print("; hits, fire range (0 = none), beats between its shots; the enemy")
    print("; shots' speed and life; the shield the warp into it restores;")
    print("; its card's caption, from levels. The ladder's sectors, then the")
    print("; loop's: the same tables, harder, which sector_next goes back to")
    print("; (sect_loop) after the last. Then the tables: mesh, flags, x, z,")
    print("; centre height, heading, hits, timer (a crystal's first launch);")
    print("; -1 ends one. Then the captions.")
    print(f"nsect       equ     {len(lap) + len(loop)}")
    print(f"sect_loop   equ     {len(lap)}")
    print("sec_dir:")
    for n, (i, _, r, dly, _) in enumerate(lap + loop, 1):
        cap = f"cap_{i}" if n <= len(lap) else "cap_loop"
        print(f"        dc.w    lv_{i}-levels,{SPAWN[0]},{SPAWN[1]},0,"
              f"{dly}         ; sector {n}")
        print(f"        dc.w    {r['own']},{r['alert']}")
        print("        dc.b    " + ",".join(f"gt_{t}-gltypes" for t in r["mix"]))
        print(f"        dc.w    {r['ghp']},{r['frange']},{r['fcd']},"
              f"{r['esv']},{round(ESHOT_RANGE / r['esv'])},{r['gain']}")
        print(f"        dc.w    {cap}-levels")
    assert SD_SIZE == 2 * 5 + 2 * 2 + MIX_N + 2 * 6 + 2
    print(f"        ifne    sd_size-{SD_SIZE}")
    print('        fail    "levels.inc: a record is not sd_size (genlevel.py vs equates.inc)"')
    print("        endc")
    print("levels:")
    for i, ents, _, _, _ in lap:
        cfg = SECTORS[i - 1]
        what = "the M3 test sector" if "fixed" in cfg else f"seed {cfg['seed']}"
        n = sum(1 for e in ents if e[0] == "gen")
        print(f"lv_{i}:                               ; sector {i}: {what}, "
              f"{n} crystals, {len(ents)} entities")
        for kind, x, z, h, t in ents:
            print(f"        dc.w    msh_{kind},1,{x},{z},{HEIGHT[kind]},"
                  f"{h}<<8,0,{t}")
        print("        dc.w    -1")
    for i, _, _, _, cap in lap:
        print(f"cap_{i}:  dc.b    '{cap}',0")
    print(f"cap_loop:")
    print(f"        dc.b    '{LOOP_CAPTION}',0")
    print("        even")


def preview(lap, path):
    from genfont import png
    n, size = len(lap), 256
    w, h = size * n + 8 * (n - 1), size
    pix = [[(0, 0, 0)] * w for _ in range(h)]
    col = {"tower": (0, 200, 0), "block": (0, 120, 0), "mine": (255, 0, 0),
           "gen": (255, 255, 255)}
    for k, (_, ents, _, _, _) in enumerate(lap):
        ox = k * (size + 8)

        def dot(x, z, c, r):
            px = ox + int((wrap(x - SPAWN[0]) + 4096) * size / SECTOR)
            pz = int((4096 - wrap(z - SPAWN[1])) * size / SECTOR)
            for dx in range(-r, r + 1):
                for dz in range(-r, r + 1):
                    if 0 <= pz + dz < h and ox <= px + dx < ox + size:
                        pix[pz + dz][px + dx] = c
        for y in range(h):
            for x in (ox, ox + size - 1):
                pix[y][x] = (40, 40, 40)
        for x in range(ox, ox + size):
            pix[0][x] = pix[h - 1][x] = (40, 40, 40)
        dot(*SPAWN, (0, 120, 255), 2)
        for kind, x, z, _, _ in ents:
            dot(x, z, col[kind], 3 if kind == "gen" else 1)
    png(path, pix, w, h)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--png", help="write the maps instead of the tables")
    args = ap.parse_args()
    lap, loop = build()
    for n, (i, ents, r, dly, cap) in enumerate(lap + loop, 1):
        k = {k: sum(1 for e in ents if e[0] == k) for k in HEIGHT}
        print(f"; sector {n} ({cap}): " + ", ".join(
              f"{v} {k}s" for k, v in k.items()) + f"; delay={dly} "
              + " ".join(f"{k}={'/'.join(t[0] for t in v) if k == 'mix' else v}"
                         for k, v in r.items()), file=sys.stderr)
    if args.png:
        preview(lap, args.png)
    else:
        emit(lap, loop)


if __name__ == "__main__":
    main()
